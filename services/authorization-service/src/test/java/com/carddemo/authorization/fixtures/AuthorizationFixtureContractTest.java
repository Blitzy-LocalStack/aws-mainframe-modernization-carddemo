    /**
     * Confirms the purge pair's detail amounts reproduce its parent summary's counters exactly.
     *
     * <p>Assumptions: this is the summary-to-detail correspondence assertion, and it is arithmetic
     * rather than a shared key because the detail segment carries no account identifier -- the IMS
     * parent-child relation supplied it. Summing the children's amounts by response code and
     * comparing against the parent's two counters and two totals is the strongest correspondence the
     * two layouts admit.</p>
     */
    @Test
    @DisplayName("the purge children's amounts reproduce their parent summary's counters exactly")
    void purgeChildrenCorrespondToTheirParentSummary() {
        Map<String, Object> parent = FixedWidthCodec.decodeRecord(
                bytesOf("pautsum0-purge-parent.bin"), CopybookLayout.layout("PAUTSUM0"));

        RecordSpec detailSpec = CopybookLayout.layout("PAUTDTL");
        byte[] children = bytesOf("pautdtl-purge-children.bin");
        int recordCount = children.length / detailSpec.reclen();

        int approvedCount = 0;
        int declinedCount = 0;
        Money approvedTotal = Money.of("0.00");
        Money declinedTotal = Money.of("0.00");
        for (int ordinal = 0; ordinal < recordCount; ordinal++) {
            Map<String, Object> child = FixedWidthCodec.decodeRecord(
                    recordAt(children, ordinal, detailSpec.reclen()), detailSpec);
            Money amount = Money.of(amountField(child, "PA-TRANSACTION-AMT"));
            if ("00".equals(textField(child, "PA-AUTH-RESP-CODE"))) {
                approvedCount++;
                approvedTotal = approvedTotal.plus(amount);
            } else {
                declinedCount++;
                declinedTotal = declinedTotal.plus(amount);
            }
        }

        assertThat(recordCount).isEqualTo(4);
        assertThat(approvedCount)
                .isEqualTo(amountField(parent, "PA-APPROVED-AUTH-CNT").intValueExact());
        assertThat(declinedCount)
                .isEqualTo(amountField(parent, "PA-DECLINED-AUTH-CNT").intValueExact());
        assertThat(approvedTotal.amount())
                .isEqualByComparingTo(amountField(parent, "PA-APPROVED-AUTH-AMT"));
        assertThat(declinedTotal.amount())
                .isEqualByComparingTo(amountField(parent, "PA-DECLINED-AUTH-AMT"));
    }

    /**
     * Confirms a declined child carries a zero approved amount.
     *
     * <p>Assumptions: this is asserted separately from the totals above, because a declined record
     * whose approved amount equalled its requested amount would leave the two parent totals correct
     * while publishing an approval that never happened.</p>
     */
    @Test
    @DisplayName("a declined authorization carries a zero approved amount")
    void aDeclinedChildCarriesNoApprovedAmount() {
        RecordSpec spec = CopybookLayout.layout("PAUTDTL");
        byte[] children = bytesOf("pautdtl-purge-children.bin");

        for (int ordinal = 0; ordinal < children.length / spec.reclen(); ordinal++) {
            Map<String, Object> child =
                    FixedWidthCodec.decodeRecord(recordAt(children, ordinal, spec.reclen()), spec);
            if (!"00".equals(textField(child, "PA-AUTH-RESP-CODE"))) {
                assertThat(amountField(child, "PA-APPROVED-AMT")).isEqualByComparingTo("0.00");
                assertThat(textField(child, "PA-MATCH-STATUS")).isEqualTo("D");
            }
        }
    }

    /**
     * Confirms the two unload fixtures carry the same two accounts in opposite orders.
     *
     * <p>Assumptions: the pair is asserted as a pair. Each file alone would be satisfied by a reader
     * that sorted its output, and it is exactly that sort which would destroy the unload order the
     * two files exist to distinguish.</p>
     */
    @Test
    @DisplayName("the two unload fixtures carry the same accounts in opposite orders")
    void theUnloadFixturesCarryOppositeOrders() {
        assertThat(unloadedAccounts("unload-gsam-summary-100.bin"))
                .containsExactly("10000000001", "10000000002");
        assertThat(unloadedAccounts("unload-prefixed-summary-100.bin"))
                .containsExactly("10000000002", "10000000001");
        assertThat(unloadedAccounts("unload-gsam-summary-100.bin"))
                .containsExactlyInAnyOrderElementsOf(
                        unloadedAccounts("unload-prefixed-summary-100.bin"));
    }

    /**
     * Confirms a decode-only fixture's negatively-signed zero reads as an unsigned zero.
     *
     * <p>Assumptions: the sign is asserted through {@link BigDecimal#signum()} as well as through
     * equality, because {@code new BigDecimal("-0.00").compareTo(BigDecimal.ZERO)} is zero -- an
     * equality check alone would pass for the very value the normalisation exists to prevent.</p>
     *
     * @param name the decode-only fixture under test
     * @param layoutName the registry layout it is written against
     * @param moneyField the money field carrying the negatively-signed zero
     */
    @ParameterizedTest
    @CsvSource({
        "pautsum0-negative-zero-decode-only.bin, PAUTSUM0, PA-CASH-BALANCE",
        "pautdtl-negative-zero-decode-only.bin, PAUTDTL, PA-TRANSACTION-AMT",
        "pautdtl-negative-zero-decode-only.bin, PAUTDTL, PA-APPROVED-AMT",
    })
    @DisplayName("a negatively-signed packed zero decodes as an unsigned zero")
    void aNegativelySignedZeroDecodesUnsigned(String name, String layoutName, String moneyField) {
        Map<String, Object> fields =
                FixedWidthCodec.decodeRecord(bytesOf(name), CopybookLayout.layout(layoutName));
        BigDecimal decoded = amountField(fields, moneyField);

        assertThat(decoded).isEqualByComparingTo("0.00");
        assertThat(decoded.signum()).isZero();
    }

    /**
     * Confirms a value-bearing trailing filler survives the decode instead of being blanked.
     *
     * @param name the fixture whose filler carries content
     * @param layoutName the registry layout it is written against
     */
    @ParameterizedTest
    @CsvSource({
        "pautsum0-filler-nonblank.bin, PAUTSUM0",
        "pautdtl-filler-nonblank.bin, PAUTDTL",
    })
    @DisplayName("a value-bearing trailing filler is preserved, not rebuilt as blanks")
    void aValueBearingFillerIsPreserved(String name, String layoutName) {
        RecordSpec spec = CopybookLayout.layout(layoutName);
        byte[] record = bytesOf(name);
        Map<String, Object> fields = FixedWidthCodec.decodeRecord(record, spec);

        assertThat(textField(fields, "FILLER")).isNotEmpty().isNotBlank();
        assertThat(FixedWidthCodec.encodeRecordPreservingSign(fields, spec, record))
                .isEqualTo(record);
    }

    /**
     * Confirms terminator-shaped bytes inside a field are data and not a record boundary.
     *
     * <p>Assumptions: the RECORD COUNT is asserted as well as the content, because a reader that split
     * on a terminator would produce a different number of records, and that is the failure mode the
     * fixture exists to catch. Asserting only the field content would pass for a reader that split and
     * then re-padded.</p>
     *
     * @param name the terminator fixture under test
     */
    @ParameterizedTest
    @ValueSource(strings = {
        "pautsum0-line-terminator-bytes.bin",
        "pautdtl-line-terminator-bytes.bin",
    })
    @DisplayName("terminator-shaped bytes inside a field never split a record")
    void terminatorBytesNeverSplitARecord(String name) {
        String layoutName = name.startsWith("pautsum0") ? "PAUTSUM0" : "PAUTDTL";
        RecordSpec spec = CopybookLayout.layout(layoutName);
        byte[] image = bytesOf(name);

        assertThat(image.length / spec.reclen()).isEqualTo(2);
        assertThat(new String(image, StandardCharsets.US_ASCII))
                .as("%s carries at least one terminator-shaped byte", name)
                .containsAnyOf("\n", "\r", "\u0015", "\u0025");

        for (int ordinal = 0; ordinal < 2; ordinal++) {
            byte[] record = recordAt(image, ordinal, spec.reclen());
            assertThat(record).hasSize(spec.reclen());
            assertThat(FixedWidthCodec.encodeRecordPreservingSign(
                    FixedWidthCodec.decodeRecord(record, spec), spec, record)).isEqualTo(record);
        }
    }

    /**
     * Confirms a truncated binary record is refused rather than decoded as a whole one.
     */
    @Test
    @DisplayName("a truncated binary record is refused, not decoded short")
    void aTruncatedBinaryRecordIsRefused() {
        RecordSpec spec = CopybookLayout.layout("PAUTDTL");
        byte[] record = bytesOf("pautdtl-canonical.bin");
        byte[] truncated = new byte[record.length - 1];
        System.arraycopy(record, 0, truncated, 0, truncated.length);

        assertThatThrownBy(() -> FixedWidthCodec.decodeRecord(truncated, spec))
                .isInstanceOf(RuntimeException.class);
    }

    /**
     * Returns the account identifiers of an unload fixture, in the order the file stores them.
     *
     * @param name the unload fixture resource name
     * @return one account identifier per record, in file order
     */
    private static List<String> unloadedAccounts(String name) {
        RecordSpec spec = CopybookLayout.layout("PAUTSUM0");
        byte[] image = bytesOf(name);

        List<String> accounts = new ArrayList<>();
        for (int ordinal = 0; ordinal < image.length / spec.reclen(); ordinal++) {
            Map<String, Object> fields =
                    FixedWidthCodec.decodeRecord(recordAt(image, ordinal, spec.reclen()), spec);
            accounts.add(amountField(fields, "PA-ACCT-ID").toBigIntegerExact().toString());
        }
        return accounts;
    }
