    /**
     * Reads one fixture resource as raw bytes.
     *
     * @param name the resource name below the fixture root
     * @return the resource's bytes, exactly as stored
     * @throws AssertionError if the resource is not on the test classpath
     * @throws UncheckedIOException if the resource cannot be read once opened
     */
    private static byte[] bytesOf(String name) {
        try (InputStream stream = AuthorizationFixtureContractTest.class.getClassLoader()
                .getResourceAsStream(FIXTURE_ROOT + name)) {
            if (stream == null) {
                throw new AssertionError("fixture " + name + " is not on the test classpath");
            }
            return stream.readAllBytes();
        } catch (IOException failure) {
            throw new UncheckedIOException("fixture " + name + " could not be read", failure);
        }
    }

    /**
     * Reads one fixture resource as its lines, dropping a trailing newline only.
     *
     * <p>Assumptions: the split is on the newline alone and empty trailing entries are removed, so a
     * file whose last line ends with a terminator yields the same line count as one whose last line
     * does not. Every payload width asserted below is therefore the width of the payload rather than
     * of the payload plus a terminator.</p>
     *
     * @param name the resource name below the fixture root
     * @return the resource's lines with no terminator characters
     */
    private static List<String> linesOf(String name) {
        List<String> lines = new ArrayList<>();
        for (String line : new String(bytesOf(name), StandardCharsets.US_ASCII).split("\n")) {
            String stripped = line.endsWith("\r") ? line.substring(0, line.length() - 1) : line;
            if (!stripped.isEmpty()) {
                lines.add(stripped);
            }
        }
        return lines;
    }

    /**
     * Slices one fixed-length record out of a multi-record fixture.
     *
     * @param image the whole fixture image
     * @param ordinal the zero-based record ordinal
     * @param reclen the record length the layout declares
     * @return exactly {@code reclen} bytes beginning at the ordinal's offset
     */
    private static byte[] recordAt(byte[] image, int ordinal, int reclen) {
        byte[] record = new byte[reclen];
        System.arraycopy(image, ordinal * reclen, record, 0, reclen);
        return record;
    }

    /**
     * Returns one decoded field as text with its trailing blanks removed.
     *
     * @param fields the decoded record
     * @param name the copybook field name
     * @return the field's characters with trailing blanks stripped
     */
    private static String textField(Map<String, Object> fields, String name) {
        return String.valueOf(fields.get(name)).stripTrailing();
    }

    /**
     * Returns one decoded field as an exact decimal.
     *
     * @param fields the decoded record
     * @param name the copybook field name
     * @return the field's value as a {@link BigDecimal}
     */
    private static BigDecimal amountField(Map<String, Object> fields, String name) {
        return new BigDecimal(String.valueOf(fields.get(name)));
    }

