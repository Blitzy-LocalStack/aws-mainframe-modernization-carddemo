    @ParameterizedTest
    @MethodSource("everyBinaryFixture")
    @DisplayName("every binary fixture divides into whole records of its declared length")
    void everyBinaryFixtureDividesIntoWholeRecords(String name, String layoutName) {
        RecordSpec spec = CopybookLayout.layout(layoutName);
        byte[] image = bytesOf(name);

        assertThat(image.length % spec.reclen())
                .as("fixture %s against %s-byte records", name, spec.reclen())
                .isZero();
        assertThat(image.length / spec.reclen()).isPositive();
    }

    /**
     * Confirms every record of every binary fixture decodes and re-encodes byte-identically.
     *
     * <p>Assumptions: byte identity on re-encode is the strongest property available here and it is
     * what proves the decode lost nothing -- not a sign, not a pad nibble, not a filler byte. It is
     * asserted for every record of every fixture, because a fixture family whose first record round
     * trips and whose fourth does not is exactly the case a single-record test misses.</p>
     *
     * <p>Trade-offs: the sign-preserving encoder is used rather than the plain one, because a
     * negatively-signed packed zero re-encodes to the POSITIVE sign nibble under the plain encoder --
     * documented divergence {@code D-SIGNED-ZERO-PACKED} -- so the two decode-only fixtures would fail
     * byte identity for a reason that is a deliberate normalisation rather than a loss.</p>
     *
     * @param name the fixture resource name
     * @param layoutName the registry layout the fixture is written against
     */
    @ParameterizedTest
    @MethodSource("everyBinaryFixture")
    @DisplayName("every record of every binary fixture round trips byte-identically")
    void everyBinaryRecordRoundTripsByteIdentically(String name, String layoutName) {
        RecordSpec spec = CopybookLayout.layout(layoutName);
        byte[] image = bytesOf(name);

        for (int ordinal = 0; ordinal < image.length / spec.reclen(); ordinal++) {
            byte[] record = recordAt(image, ordinal, spec.reclen());
            Map<String, Object> fields = FixedWidthCodec.decodeRecord(record, spec);

            assertThat(fields).as("record %s of %s", ordinal, name).isNotEmpty();
            assertThat(FixedWidthCodec.encodeRecordPreservingSign(fields, spec, record))
                    .as("record %s of %s re-encodes byte-identically", ordinal, name)
                    .isEqualTo(record);
        }
    }

